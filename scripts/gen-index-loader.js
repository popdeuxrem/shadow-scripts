#!/usr/bin/env node
/**
 * scripts/gen-index-loader.js — Cyberpunk Loader Generator
 * ──────────────────────────────────────────────────────────────
 * Generates the unified index.html loader in cyberpunk neon style
 * - Embeds all payloads from manifest.json
 * - Auto-injects scripts based on domain/app
 * - Displays QR codes, proxies, tokens, and active scripts
 * - Neon cyberpunk UI + ASCII header
 * - Supports --ci for JSON summary
 */

import fs from "fs/promises";
import path from "path";

const ROOT = path.resolve(new URL(import.meta.url).pathname, "..", "..");
const PUBLIC = path.join(ROOT, "apps/loader/public");
const SCRIPTS = path.join(ROOT, "scripts");
const MANIFEST_PATH = path.join(PUBLIC, "manifest.json");
const OUT_FILE = path.join(PUBLIC, "index.html");

const argv = process.argv.slice(2);
const opts = { ci: argv.includes("--ci") };

async function exists(p) {
  try { await fs.access(p); return true; }
  catch { return false; }
}

async function loadManifest() {
  const raw = await fs.readFile(MANIFEST_PATH, "utf8");
  return JSON.parse(raw);
}

